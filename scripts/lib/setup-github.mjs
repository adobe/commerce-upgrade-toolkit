import fs from 'fs-extra';
import { buildManifest, writeManifest } from './integrity.mjs';
import path from 'path';
import { reconcileLegacyCodegraph, validateCodegraphOptions } from './codegraph-policy.mjs';
import {
  copyIfExists,
  copyDirFull,
  copyDirSplit,
  copyLegalNotices,
  upsertGitignoreBlock,
  CONTEXT_PROJECT_OWNED,
  writeInstalledVersion,
  preflightVersionMarker,
  assertToolkitComplete,
  warnPreservedPermissionProfile,
} from './sync-assets.mjs';

/**
 * Install the GitHub Copilot toolkit (.github assets, copilot-instructions.md,
 * .gitignore rules) — the canonical .github/{agents,skills,prompts,instructions,hooks,
 * context,scripts} tree generated by scripts/generate-github-assets.mjs from the
 * .claude/* source of truth. CodeGraph is disabled; findings use direct source evidence.
 */
export async function runGithubCopilotSetup({ toolRoot, projectRoot, installType, environment, ...options }) {
  validateCodegraphOptions(options);
  await assertToolkitComplete(toolRoot, 'github-copilot');
  await preflightVersionMarker(projectRoot, 'github-copilot');
  await warnPreservedPermissionProfile(toolRoot, projectRoot, 'github-copilot');
  reconcileLegacyCodegraph(projectRoot, options);
  const githubDir = path.join(projectRoot, '.github');
  await fs.ensureDir(githubDir);

  const copied = [];

  copied.push(...await copyLegalNotices(toolRoot, projectRoot, 'github-copilot'));

  copied.push(...await copyDirFull(
    path.join(toolRoot, '.github', 'agents'),
    path.join(githubDir, 'agents'),
    '.github/agents/'
  ));

  copied.push(...await copyDirFull(
    path.join(toolRoot, '.github', 'skills'),
    path.join(githubDir, 'skills'),
    '.github/skills/'
  ));

  copied.push(...await copyDirFull(
    path.join(toolRoot, '.github', 'prompts'),
    path.join(githubDir, 'prompts'),
    '.github/prompts/'
  ));

  copied.push(...await copyDirFull(
    path.join(toolRoot, '.github', 'instructions'),
    path.join(githubDir, 'instructions'),
    '.github/instructions/'
  ));

  copied.push(...await copyDirFull(
    path.join(toolRoot, '.github', 'hooks'),
    path.join(githubDir, 'hooks'),
    '.github/hooks/'
  ));

  copied.push(...await copyDirFull(
    path.join(toolRoot, '.github', 'scripts'),
    path.join(githubDir, 'scripts'),
    '.github/scripts/'
  ));

  copied.push(...await copyDirSplit(
    path.join(toolRoot, '.github', 'context'),
    path.join(githubDir, 'context'),
    '.github/context/',
    CONTEXT_PROJECT_OWNED
  ));

  // --- Seed upgrade-state.md's installType/environment from wizard answers ---
  if (installType) {
    const upgradeStatePath = path.join(githubDir, 'context', 'upgrade-state.md');
    if (await fs.pathExists(upgradeStatePath)) {
      let content = await fs.readFile(upgradeStatePath, 'utf8');
      if (installType) content = content.replace(/^installType: .*$/m, `installType: ${installType}`);
      if (installType === 'fresh' && environment) content = content.replace(/^environment: .*$/m, `environment: ${environment}`);
      await fs.writeFile(upgradeStatePath, content);
      console.log(`  ℹ️  upgrade-state.md seeded: installType=${installType}${installType === 'fresh' && environment ? `, environment=${environment}` : ''}`);
    }
  }

  // --- copilot-settings-notes.md (always refresh — documentation only) ---
  if (await copyIfExists(
    path.join(toolRoot, '.github', 'copilot-settings-notes.md'),
    path.join(githubDir, 'copilot-settings-notes.md')
  )) copied.push('.github/copilot-settings-notes.md');

  // --- copilot-instructions.md (no-overwrite — developer may have local customisation) ---
  const instructionsSrc = path.join(toolRoot, '.github', 'copilot-instructions.md');
  const instructionsDest = path.join(githubDir, 'copilot-instructions.md');
  if (!await fs.pathExists(instructionsDest)) {
    if (await copyIfExists(instructionsSrc, instructionsDest)) copied.push('.github/copilot-instructions.md');
  } else {
    console.log('  ℹ️  .github/copilot-instructions.md already exists — skipped (keeping existing).');
  }

  // --- docs/ ---
  await fs.ensureDir(path.join(projectRoot, 'docs'));
  // Report destinations the documentation agent writes to; it cannot create parent directories.
  await fs.ensureDir(path.join(githubDir, 'reports'));
  await fs.ensureDir(path.join(projectRoot, 'output'));
  if (await copyIfExists(
    path.join(toolRoot, 'docs', 'upgrade-workflow.md'),
    path.join(projectRoot, 'docs', 'upgrade-workflow.md')
  )) copied.push('docs/upgrade-workflow.md');

  // --- .gitignore ---
  const gitignorePath = path.join(projectRoot, '.gitignore');
  const gitignore = await fs.pathExists(gitignorePath)
    ? await fs.readFile(gitignorePath, 'utf8')
    : '';

  const blockStart = '# --- Adobe Commerce Upgrade Toolkit ---';
  const blockEnd = '# --- End Adobe Commerce Upgrade Toolkit ---';
  const blockBody = [
    '.github/quality-log.jsonl',
    '/.claude/context/.uct-capture-*/',
    '/.github/context/.uct-capture-*/',
    '/.ccua-reconcile-*/',
    '/.vscode/.ccua-reconcile-*/',
    '/.claude/.ccua-reconcile-*/',
    '/.ccua/'
  ].join('\n');

  await fs.writeFile(gitignorePath, upsertGitignoreBlock(gitignore, blockStart, blockEnd, blockBody));
  copied.push('.gitignore (updated)');

  // --- Version marker ---
  const { version: toolkitVersion } = await fs.readJson(path.join(toolRoot, 'package.json'));
  await writeManifest(projectRoot, await buildManifest(toolRoot, 'github-copilot'));
  await writeInstalledVersion(projectRoot, toolkitVersion, 'github-copilot');

  // --- Summary ---
  console.log('\n✅ Adobe Commerce Upgrade Toolkit (GitHub Copilot) setup complete');
  console.log(`\n   Project:  ${projectRoot}`);
  if (copied.length) {
    console.log('\n   Copied assets:');
    copied.forEach((item) => console.log(`     - ${item}`));
  }
  console.log('\n   Next steps:');
  console.log('     1. Open the project in VS Code with GitHub Copilot Chat enabled.');
  console.log('     2. Run the upgrade-hop skill to detect your environment and generate a hop roadmap.');
  console.log('     3. Run upgrade-hop <version> to scan and analyse the first hop.');
  console.log('     4. Run upgrade-hop-execute <version> to implement fixes for that hop.');
  console.log('     5. Run upgrade-deploy-prep once all hops are complete.');
  console.log('     6. See docs/upgrade-workflow.md for the full upgrade workflow diagram.');
  console.log('     7. See .github/copilot-settings-notes.md for the Bash-permissions/hooks gaps Copilot cannot mechanically enforce.');

  return { projectRoot, agent: 'github-copilot', copied };
}
